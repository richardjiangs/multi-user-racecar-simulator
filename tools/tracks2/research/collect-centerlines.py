"""Normalize source maps without silently substituting a different circuit layout.

Output remains geographic research data. Runtime coordinates are built separately;
the eight reviewed shared circuits are not regenerated by this importer.
"""
import json, math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ATLAS = ROOT / 'atlas/tracks'
INVENTORY = json.loads((ROOT / 'inventory.json').read_text())['tracks']
SOURCES = {
 'Algarve Circuit': 'portimao',
 'Laguna Seca': 'laguna-seca',
 'Circuit de la Sarthe': 'circuit-de-la-sarthe',
 'Circuit de la Sarthe — 2017': 'circuit-de-la-sarthe',
 'Autodromo di Imola': 'imola',
 'Autodromo Imola — 499P': 'imola',
 'Mugello Circuit': 'mugello',
 'Circuit Zandvoort': 'zandvoort',
 'Fuji Speedway': 'fuji',
 'Shanghai International Circuit': 'shanghai',
 'Watkins Glen International': 'watkins-glen',
 'Road America': 'road-america',
 'Sebring International Raceway': 'sebring',
 'Circuit de Barcelona-Catalunya': 'barcelona',
 'Daytona Road Course': 'daytona',
 'Red Bull Ring': 'red-bull-ring',
 'Autodromo Nazionale Monza': 'monza',
 'Circuit of the Americas': 'circuit-of-the-americas',
 'Bahrain International Circuit': 'bahrain',
 'Circuit Paul Ricard': 'paul-ricard',
 'Autodromo Jose Carlos Pace': 'interlagos',
 'Baku City Circuit': 'baku',
 'Miami International Autodrome': 'miami',
 'Hungaroring': 'hungaroring',
 'Las Vegas Strip Circuit': 'las-vegas',
}

def metric(points):
    lon, lat = points[0][:2]
    return [[(p[0]-lon)*111320*math.cos(math.radians(lat)),
             (p[1]-lat)*111320] for p in points]

def distance(points):
    return sum(math.dist(a, b) for a, b in zip(points, points[1:]))

out = {}
for name, slug in SOURCES.items():
    assert name in INVENTORY, name
    folder = ATLAS / slug / 'raw'
    track = json.loads((folder / 'track.json').read_text())
    layout = next((v for v in track['layouts'] if v['id'] == 'imsa'), track['layouts'][0])
    geo = json.loads((folder / layout['geometry']['centerline']).read_text())
    features = geo['features']
    line = next(v for v in features if v['geometry']['type'] == 'LineString'
                and v['properties'].get('role') == 'outline')
    points = line['geometry']['coordinates']
    corners = next(v['items'] for v in layout['point_layers'] if v['kind'] == 'corners')
    markers = next((v['items'] for v in layout['point_layers'] if v['kind'] == 'layout_points'), [])
    widths = []
    for corner in corners:
        for side in ['entry', 'exit']:
            section = corner.get(side, {})
            if 'width_m' in section and 'marker' in section:
                widths.append([section['marker'], section['width_m']/2])
    for marker in markers:
        if marker.get('line', {}).get('width_m'):
            widths.append([marker['marker'], marker['line']['width_m']/2])
    out[name] = {
        'points': points, 'closed': True, 'L': INVENTORY[name]['dist'],
        'sourceLength': layout.get('length_m'), 'measuredLength': distance(metric(points)),
        'direction': layout.get('direction'), 'widths': sorted(widths),
        'labels': [[c['marker'], c.get('labels', {}).get('official')
                    or c.get('label') or f"Turn {c['number']}"] for c in corners],
        'markers': {m['id']: m['marker'] for m in markers},
        'source': f'https://github.com/tobi/track-atlas/tree/main/tracks/{slug}',
        'sourceBasis': layout['geometry'].get('basis'),
        'review': 'pending geometry, layout, pit and elevation verification',
    }
(ROOT / 'source-centerlines.json').write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')))
print(f'Imported {len(out)} geographic layouts; no simulator files changed.')
for name, t in out.items():
    print(f"{name}: declared {t['L']} m; source {t['sourceLength']} m; mapped {t['measuredLength']:.1f} m")
